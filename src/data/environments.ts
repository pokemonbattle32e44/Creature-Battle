export const BIOME_ROTATION_ORDER: BiomeType[] = [
  'forest',
  'ocean',
  'plain',
  'desert',
  'cave',
  'mountain',
  'volcano',
  'swamp',
  'ruins',
];

export function getBiomeConfig(id?: BiomeType | string): BiomeConfig {
  if (!id || !BIOMES[id as BiomeType]) return BIOMES.forest;
  return BIOMES[id as BiomeType];
}

export function getNextBiome(current: BiomeType | string): BiomeType {
  const currentIndex = BIOME_ROTATION_ORDER.indexOf(current as BiomeType);
  if (currentIndex === -1 || currentIndex === BIOME_ROTATION_ORDER.length - 1) {
    return BIOME_ROTATION_ORDER[0];
  }
  return BIOME_ROTATION_ORDER[currentIndex + 1];
}
