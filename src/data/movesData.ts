export function getMove(moveId: string): Move {
  if (MOVES_DATABASE[moveId]) {
    return MOVES_DATABASE[moveId];
  }

  // Smart type detection from move ID string
  const idLower = moveId.toLowerCase();
  let inferredType: PokemonType = 'normal';
  let category: 'physical' | 'special' | 'status' = 'physical';
  let power = 55;

  if (idLower.match(/shadow|ghost|night|lick|astonish|hex|curse|ominous|poltergeist|phantom/)) {
    inferredType = 'ghost';
  } else if (idLower.match(/water|surf|hydro|bubble|aqua|cascade|scald|soak|whirlpool|chilling/)) {
    inferredType = 'water';
    category = 'special';
  } else if (idLower.match(/fire|ember|flame|heat|blast|burn|incinerate|lava|overheat/)) {
    inferredType = 'fire';
    category = 'special';
  } else if (idLower.match(/grass|leaf|vine|seed|spore|petal|absorb|solar|branch|trailblaze|bullet_seed/)) {
    inferredType = 'grass';
  } else if (idLower.match(/thunder|volt|spark|shock|zap|electric|nuzzle|discharge/)) {
    inferredType = 'electric';
    category = 'special';
  } else if (idLower.match(/ice|freeze|blizzard|snow|frost|avalanche|icicle|aurora/)) {
    inferredType = 'ice';
    category = 'special';
  } else if (idLower.match(/rock|stone|ancient|roll|smack/)) {
    inferredType = 'rock';
  } else if (idLower.match(/earth|mud|sand|dig|fissure|scorching|ground/)) {
    inferredType = 'ground';
  } else if (idLower.match(/air|gust|wing|fly|brave|peck|roost|feather|sky|acrobatics/)) {
    inferredType = 'flying';
  } else if (idLower.match(/poison|sludge|toxic|acid|venom|smog|gunk/)) {
    inferredType = 'poison';
    category = 'special';
  } else if (idLower.match(/bug|leech|signal|pin|string|pester|pounce|skitter/)) {
    inferredType = 'bug';
  } else if (idLower.match(/dark|bite|crunch|foul|nasty|snarl|thief|feint|knock|sucker/)) {
    inferredType = 'dark';
  } else if (idLower.match(/fairy|gleam|moon|charm|kiss|play|dazzle|disarm|spirit/)) {
    inferredType = 'fairy';
    category = 'special';
  } else if (idLower.match(/psychic|psy|mind|confus|calm|zen|future|extra/)) {
    inferredType = 'psychic';
    category = 'special';
  } else if (idLower.match(/dragon|draco|outrage|twister|scale/)) {
    inferredType = 'dragon';
  } else if (idLower.match(/steel|iron|metal|bullet|flash|magnet/)) {
    inferredType = 'steel';
  } else if (idLower.match(/karate|close|punch|kick|chop|mach|force|brick|drain_punch|hammer|press/)) {
    inferredType = 'fighting';
  }

  // Fallback dynamic move
  return {
    id: moveId,
    name: moveId.split(/_|-/).map((s) => s.charAt(0).toUpperCase() + s.slice(1)).join(' '),
    type: inferredType,
    category,
    power,
    accuracy: 100,
    pp: 20,
    maxPp: 20,
    description: `Ataque do tipo ${inferredType.toUpperCase()}.`,
  };
}
